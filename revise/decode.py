"""Revision decoding: at every step the model either WRITES the next token
(writer stream) or FIXES one token inside the window (re-read stream), never
both. After a fix, an erasure policy decides which later tokens are erased;
erased tokens in the middle of the text become <mask> and are regenerated by
filling (re-read stream), an erased tail is simply truncated and re-written.

Erasure policies (= the compared variants):
  none      -- fix only, keep everything after the fix          (variant 2)
  suffix    -- erase everything after the fix                   (variant 3)
  dep       -- erase tokens predicted dependent by the dep head (variant 4)
  oracle    -- erase true dependents from the generator's graph (variant 5)
  lines     -- dep head, but erase whole solution lines         (variant 6)
  random    -- erase as many random tokens as `dep` would       (variant 7)
  confdrop  -- measure the confidence drop with extra passes    (variant 4b)
"""

import collections
import math
import random
from dataclasses import dataclass, field

import numpy as np
import torch
import torch.nn.functional as F

from .examples import erase, window_start
from .igsm.checker import ERR, analyze, descendants, line_ids
from .model import build_mask
from .rollout import generate


@dataclass
class Policy:
    name: str = "dep_head"
    revise: bool = True
    erase: str = "dep"
    window: int = 64
    tau_err: float = 0.5
    tau_dep: float = 0.5
    max_fixes: int = 8
    slack: int = 4
    slack_min_len: int = 3
    check_every: int = 1
    confdrop_delta: float = 2.0
    confdrop_iters: int = 6
    confdrop_mode: str = "writer"
    require_disagree: bool = True  # fix only where the fix head prefers another token
    detect: str = "model"  # model: error head decides | oracle: checker finds the true first error
    oracle_delay: int = 24  # oracle detection fixes an error only this many tokens after it was written
    oracle_scan_every: int = 4
    max_sol_len: int = 600
    diagnostics: bool = True


VARIANTS = {
    # name: (uses revision model, revise, erase policy)
    "plain": (False, False, "none"),                 # 1. plain model, no revision
    "fix_only": (True, True, "none"),                # 2. revision without erasing
    "erase_suffix": (True, True, "suffix"),          # 3. erase all text after the error
    "dep_head": (True, True, "dep"),                 # 4. erase only dependent tokens (head)
    "oracle_dep": (True, True, "oracle"),            # 5. erase true dependents (upper bound)
    "dep_head_lines": (True, True, "lines"),         # 6. erase whole lines with dependents
    "random_erase": (True, True, "random"),          # 7. random erasure, same amount as 4
    "confdrop_measure": (True, True, "confdrop"),    # 4b. dependency by measured confidence drop
    "revision_model_no_revision": (True, False, "none"),  # diagnostic
}


def make_policy(variant, base: dict):
    _, revise, er = VARIANTS[variant]
    p = Policy(name=variant, revise=revise, erase=er)
    for k, v in (base or {}).items():
        if hasattr(p, k) and not (k == "tau_err" and v == "auto"):
            setattr(p, k, v)
    return p


@dataclass
class Slot:
    idx: int
    prob: object
    sol: list = field(default_factory=list)
    steps: int = 0
    tokens: int = 0
    dirty: int = 0  # earliest absolute position whose causal state is stale
    fixes: int = 0
    fills: int = 0
    erased: int = 0
    since_check: int = 0
    known_err: tuple = None  # oracle detection: (position, valid tokens) of the first error
    last_scan: int = -10 ** 9
    done: bool = False
    events: list = field(default_factory=list)


def pack(items, pad, device):
    """items: list of (causal_ids, copy_ids or None, copy_start_abs)."""
    B = len(items)
    L = max(len(c) + (len(w) if w else 0) for c, w, _ in items)
    ids = np.full((B, L), pad, dtype=np.int64)
    pos = np.zeros((B, L), dtype=np.int64)
    is_copy = np.zeros((B, L), dtype=bool)
    wstart = np.zeros((B, L), dtype=np.int64)
    valid = np.zeros((B, L), dtype=bool)
    last, coff, clen = [], [], []
    for b, (c, w, s) in enumerate(items):
        n = len(c)
        ids[b, :n] = c
        pos[b, :n] = np.arange(n)
        valid[b, :n] = True
        last.append(n - 1)
        coff.append(n)
        m = len(w) if w else 0
        clen.append(m)
        if m:
            ids[b, n:n + m] = w
            pos[b, n:n + m] = np.arange(s, s + m)
            is_copy[b, n:n + m] = True
            wstart[b, n:n + m] = s
            valid[b, n:n + m] = True
    t = lambda a: torch.from_numpy(a).to(device, non_blocking=True)
    ids, pos, is_copy, wstart, valid = t(ids), t(pos), t(is_copy), t(wstart), t(valid)
    wid = torch.zeros_like(ids)
    mask = build_mask(pos, is_copy, wstart, wid, valid)
    return ids, pos, is_copy, mask, last, coff, clen


class Runner:
    """Runs packed forward passes and returns head outputs. `model` provides the
    re-read heads (error / fix / dependency); `writer` (default: the same model)
    provides the next-token distribution."""

    def __init__(self, model, tok, device, amp_dtype=None, writer=None):
        self.model, self.tok, self.device = model, tok, device
        self.writer = writer if writer is not None else model
        self.separate = self.writer is not self.model
        self.amp = amp_dtype if device.type == "cuda" else None
        V = len(tok)
        self.no_fix = torch.zeros(V, dtype=torch.bool, device=device)
        self.no_fix[tok.no_fix_ids] = True
        self.no_fill = torch.zeros(V, dtype=torch.bool, device=device)
        self.no_fill[tok.no_fill_ids] = True

    @torch.no_grad()
    def forward(self, items):
        if not self.separate:
            out = self._forward(self.model, items)
            out["h_w"], out["ids_w"] = out["h"], out["ids"]
            return out
        ow = self._forward(self.writer, [(c, None, 0) for c, _, _ in items], heads=False)
        if any(w for _, w, _ in items):
            out = self._forward(self.model, items)
        else:
            out = {"coff": ow["coff"], "clen": ow["clen"]}
        out["lm"], out["h_w"], out["ids_w"] = ow["lm"], ow["h"], ow["ids"]
        return out

    def _forward(self, model, items, heads=True):
        ids, pos, is_copy, mask, last, coff, clen = pack(items, self.tok.pad, self.device)
        with torch.autocast(self.device.type, dtype=self.amp, enabled=self.amp is not None):
            h = model(ids, pos, is_copy.long(), mask)
        B = len(items)
        ar = torch.arange(B, device=self.device)
        out = {"h": h, "ids": ids, "coff": coff, "clen": clen}
        out["lm"] = model.lm_logits(h[ar, torch.tensor(last, device=self.device)]).float()
        Wm = max(clen) if heads else 0
        if Wm > 0:
            idx = torch.tensor(coff, device=self.device)[:, None] + torch.arange(Wm, device=self.device)[None]
            cvalid = torch.arange(Wm, device=self.device)[None] < torch.tensor(clen, device=self.device)[:, None]
            idx = torch.where(cvalid, idx, torch.zeros_like(idx))
            hc = h[ar[:, None], idx]  # (B, Wm, d)
            ctok = ids[ar[:, None], idx]
            out["hc"], out["cvalid"], out["ctok"] = hc, cvalid, ctok
            out["err"] = torch.sigmoid(self.model.err_logits(hc).float())
            fl = self.model.fix_logits(hc).float()
            out["logp_tok"] = torch.log_softmax(fl, -1).gather(-1, ctok.unsqueeze(-1)).squeeze(-1)
            fill = fl.masked_fill(self.no_fill, -1e9)
            out["fill"] = fill.argmax(-1)
            fx = fl.masked_fill(self.no_fix, -1e9)
            cur = fl.gather(-1, ctok.unsqueeze(-1))
            out["disagree"] = fx.scatter(-1, ctok.unsqueeze(-1), cur).argmax(-1) != ctok
            out["fix"] = fx.scatter(-1, ctok.unsqueeze(-1), -1e9).argmax(-1)
        return out

    @torch.no_grad()
    def writer_logp(self, out, b, positions):
        """Writer log-prob of the tokens at causal `positions` of row b, and the
        writer's own prediction there."""
        p = torch.tensor(positions, device=self.device)
        logits = self.writer.lm_logits(out["h_w"][b, p - 1]).float()
        lp = torch.log_softmax(logits, -1).gather(-1, out["ids_w"][b, p].unsqueeze(-1)).squeeze(-1)
        return lp.tolist(), logits.argmax(-1).tolist()

    @torch.no_grad()
    def dep_row(self, out, b, i):
        hc = out["hc"][b, : out["clen"][b]]
        return torch.sigmoid(self.model.dep_logits(hc[i], hc).float())  # (Wb,)


def _lines_erasure(sol, j, D, tok):
    if not D:
        return []
    lines = line_ids(sol, tok)
    hit = {lines[k] for k in D}
    return [k for k in range(j + 1, len(sol)) if lines[k] in hit]


def decode_revision(model, problems, policy: Policy, tok, device, batch_size=64, amp_dtype=None, seed=0,
                    n_params=None, log_every=0, writer=None):
    runner = Runner(model, tok, device, amp_dtype, writer=writer)
    MASK, NULL, EOS = tok.mask, tok.null, tok.eos
    queue = collections.deque(enumerate(problems))
    slots, results = [], [None] * len(problems)
    W = policy.window
    max_steps = 4 * policy.max_sol_len
    n_done = 0
    while queue or slots:
        while len(slots) < batch_size and queue:
            i, p = queue.popleft()
            slots.append(Slot(idx=i, prob=p))
        items, metas = [], []
        for s in slots:
            P = len(s.prob.prompt_ids)
            has_mask = MASK in s.sol
            ended = bool(s.sol) and s.sol[-1] == EOS
            check = has_mask or (policy.revise and bool(s.sol)
                                 and (ended or s.since_check + 1 >= policy.check_every))
            ws = window_start(s.sol, W, MASK) if check else len(s.sol)
            copy = s.sol[ws:] if check else None
            items.append((s.prob.prompt_ids + s.sol, copy, P + ws))
            metas.append((P, ws, check))
            new_causal = P + len(s.sol) - s.dirty
            s.tokens += new_causal * (2 if (runner.separate and check) else 1) + (len(copy) if copy else 0)
            s.dirty = P + len(s.sol)
            s.steps += 1
        out = runner.forward(items)
        lm_next = out["lm"].argmax(-1).tolist()
        has_copy = "err" in out
        if has_copy:
            err = out["err"].masked_fill(~out["cvalid"], 0.0)
            ctok = out["ctok"]
            bad = (ctok == MASK) | (ctok == NULL)
            if policy.require_disagree:
                bad = bad | ~out["disagree"]
            err = err.masked_fill(bad, 0.0)
            err_max, err_arg = err.max(-1)
            err_max, err_arg = err_max.tolist(), err_arg.tolist()
            fill_tok, fix_tok = out["fill"].tolist(), out["fix"].tolist()

        fixing = []  # (slot index, b, i, j, new_tok)
        for b, s in enumerate(slots):
            P, ws, check = metas[b]
            sol = s.sol
            if check and MASK in sol:
                m = sol.index(MASK)
                t = fill_tok[b][m - ws]
                if t == NULL:
                    e = m
                    while e < len(sol) and sol[e] == MASK:
                        e += 1
                    s.sol = sol[:m] + sol[e:]
                else:
                    sol[m] = t
                s.fills += 1
                s.dirty = min(s.dirty, P + m)
                s.since_check = 0
                s.known_err, s.last_scan = None, -10 ** 9
            elif check and policy.detect == "oracle" and s.fixes < policy.max_fixes \
                    and (oe := _oracle_error(s, tok, policy, ws)) is not None:
                j, new = oe
                fixing.append((b, j - ws, j, new))
                s.since_check = 0
                s.known_err, s.last_scan = None, -10 ** 9
            elif check and policy.detect == "model" and s.fixes < policy.max_fixes and err_max[b] > policy.tau_err:
                i = err_arg[b]
                fixing.append((b, i, ws + i, fix_tok[b][i]))
                s.since_check = 0
            else:
                s.since_check = 0 if check else s.since_check + 1
                if sol and sol[-1] == EOS:
                    s.done = True
                else:
                    sol.append(lm_next[b])
                    if sol[-1] == EOS and not policy.revise:
                        s.done = True
            if len(s.sol) >= policy.max_sol_len or s.steps >= max_steps:
                s.done = True

        if fixing:
            _apply_fixes(runner, slots, fixing, out, policy, tok, metas, seed)

        keep = []
        for s in slots:
            if s.done:
                results[s.idx] = _finalize(s, tok, n_params)
                n_done += 1
                if log_every and n_done % log_every == 0:
                    print(f"  [{policy.name}] {n_done}/{len(problems)}", flush=True)
            else:
                keep.append(s)
        slots = keep
    return results


def _oracle_error(s, tok, policy, ws):
    """Oracle detection: the checker's first (root) error, released for fixing
    once `oracle_delay` more tokens have been written after it (or the solution
    ended / the error is about to leave the window). Returns (j, fix token)."""
    L = len(s.sol)
    ended = L > 0 and s.sol[-1] == tok.eos
    if s.known_err is None and (L - s.last_scan >= policy.oracle_scan_every or ended):
        a = analyze(s.prob, s.sol, tok)
        s.last_scan = L
        j = a.first_err
        if j is not None and a.valid[j]:
            s.known_err = (j, a.valid[j][0])
    if s.known_err is None:
        return None
    j, new = s.known_err
    if j < ws:  # fell out of the window: can no longer be fixed
        s.known_err = None
        return None
    delay = min(policy.oracle_delay, policy.window - 2)
    if L - 1 - j >= delay or ended:
        return j, new
    return None


def _apply_fixes(runner, slots, fixing, out, policy, tok, metas, seed):
    MASK = tok.mask
    dep_sets = {}
    if policy.erase in ("dep", "lines", "random"):
        for (b, i, j, new) in fixing:
            row = runner.dep_row(out, b, i).tolist()
            ws = metas[b][1]
            dep_sets[b] = [ws + k for k in range(i + 1, len(row)) if row[k] > policy.tau_dep]
    if policy.erase == "confdrop":
        dep_sets = _measure_confdrop(runner, slots, fixing, out, policy, tok, metas)

    for (b, i, j, new) in fixing:
        s = slots[b]
        P = metas[b][0]
        old = s.sol[j]
        before = list(s.sol)
        ev = {"j": j, "old": old, "new": new, "len": len(before), "lag": len(before) - 1 - j}
        an = None
        if policy.diagnostics or policy.erase == "oracle":
            an = analyze(s.prob, before, tok)
        if policy.erase == "none":
            D = []
        elif policy.erase == "suffix":
            D = list(range(j + 1, len(before)))
        elif policy.erase in ("dep", "confdrop"):
            D = dep_sets.get(b, [])
        elif policy.erase == "lines":
            D = _lines_erasure(before, j, dep_sets.get(b, []), tok)
        elif policy.erase == "random":
            n = len(dep_sets.get(b, []))
            rng = random.Random(hash((seed, s.idx, s.fixes)))
            pool = list(range(j + 1, len(before)))
            D = sorted(rng.sample(pool, min(n, len(pool))))
        elif policy.erase == "oracle":
            D = descendants(an.parents, j)
        else:
            raise ValueError(policy.erase)
        if an is not None and policy.diagnostics:
            true_d = set(descendants(an.parents, j))
            pd = set(D)
            ev.update({"true_err": an.status[j] == ERR, "is_first_err": an.first_err == j,
                       "fix_valid": an.status[j] == ERR and an.valid[j] is not None and new in an.valid[j],
                       "n_erase": len(pd), "n_true_dep": len(true_d), "tp": len(pd & true_d),
                       "had_err_before": an.first_err is not None})
        s.sol[j] = new
        if policy.erase == "suffix":
            s.sol = s.sol[: j + 1]
        elif D:
            s.sol, _ = erase(s.sol, j, D, MASK, policy.slack, policy.slack_min_len)
        s.erased += len(D)
        s.fixes += 1
        s.dirty = min(s.dirty, P + j)
        s.events.append(ev)


def _measure_confdrop(runner, slots, fixing, out, policy, tok, metas):
    """Dependency by measurement (variant 4b, and the training target of the
    dependency head): the model's confidence in every later token before vs.
    after the fix; tokens whose log-probability drops by more than delta are
    dependent. Iterated so that indirect dependents are found too."""
    if policy.confdrop_mode == "reread":
        return _measure_confdrop_reread(runner, slots, fixing, out, policy, tok, metas)
    before, cur, D, pos = {}, {}, {}, {}
    for (b, i, j, new) in fixing:
        s = slots[b]
        P = metas[b][0]
        pos[b] = [P + k for k in range(j + 1, len(s.sol))]
        before[b] = runner.writer_logp(out, b, pos[b])[0] if pos[b] else []
        cur[b] = list(s.sol)
        cur[b][j] = new
        D[b] = set()
    active = [f for f in fixing if pos[f[0]]]
    for it in range(policy.confdrop_iters):
        if not active:
            break
        items = []
        for (b, i, j, new) in active:
            s = slots[b]
            items.append((s.prob.prompt_ids + cur[b], None, 0))
            s.steps += 1
            s.tokens += len(s.sol) - j
        o = runner.forward(items)
        nxt = []
        for r, (b, i, j, new) in enumerate(active):
            P = metas[b][0]
            after, pred = runner.writer_logp(o, r, pos[b])
            found = False
            for q, k in enumerate(range(j + 1, len(cur[b]))):
                if k not in D[b] and before[b][q] - after[q] > policy.confdrop_delta:
                    D[b].add(k)
                    cur[b][k] = pred[q]  # virtual repair
                    found = True
            if found:
                nxt.append((b, i, j, new))
        active = nxt
    return {b: sorted(d) for b, d in D.items()}


def _measure_confdrop_reread(runner, slots, fixing, out, policy, tok, metas):
    MASK = tok.mask
    before = {b: out["logp_tok"][b, : out["clen"][b]].tolist() for (b, i, j, new) in fixing}
    D = {b: set() for (b, i, j, new) in fixing}
    active = list(fixing)
    for it in range(policy.confdrop_iters):
        if not active:
            break
        items = []
        for (b, i, j, new) in active:
            s = slots[b]
            P, ws, _ = metas[b]
            copy = list(s.sol[ws:])
            copy[i] = new
            for k in D[b]:
                copy[k - ws] = MASK
            items.append((s.prob.prompt_ids + s.sol[:ws], copy, P + ws))
            s.steps += 1
            s.tokens += len(copy)
        o = runner.forward(items)
        nxt = []
        for r, (b, i, j, new) in enumerate(active):
            ws = metas[b][1]
            after = o["logp_tok"][r, : o["clen"][r]].tolist()
            new_d = {ws + k for k in range(i + 1, len(after))
                     if (ws + k) not in D[b] and before[b][k] - after[k] > policy.confdrop_delta}
            if new_d:
                D[b] |= new_d
                nxt.append((b, i, j, new))
        active = nxt
    return {b: sorted(d) for b, d in D.items()}


def _finalize(s, tok, n_params):
    sol = [t for t in s.sol if t != tok.mask]
    a = analyze(s.prob, sol, tok)
    r = {"idx": s.idx, "op": s.prob.n_ops, "correct": bool(a.correct), "complete": bool(a.complete),
         "sol_correct": bool(a.complete and a.first_err is None), "steps": s.steps, "tokens": s.tokens,
         "fixes": s.fixes, "fills": s.fills, "erased": s.erased, "len": len(s.sol), "events": s.events}
    if n_params:
        r["flops"] = 2.0 * n_params * s.tokens
    return r


def decode_plain(model, problems, tok, device, batch_size=128, amp_dtype=None, max_sol_len=600, temperature=0.0,
                 n_params=None):
    results = []
    for s in range(0, len(problems), batch_size):
        chunk = problems[s: s + batch_size]
        gens, _ = generate(model, [p.prompt_ids for p in chunk], max_sol_len, tok.eos, tok.pad, device,
                           temperature=temperature, amp_dtype=amp_dtype)
        for k, (p, g) in enumerate(zip(chunk, gens)):
            a = analyze(p, g, tok)
            toks = len(p.prompt_ids) + len(g)
            r = {"idx": s + k, "op": p.n_ops, "correct": bool(a.correct), "complete": bool(a.complete),
                 "sol_correct": bool(a.complete and a.first_err is None), "steps": len(g), "tokens": toks,
                 "fixes": 0, "fills": 0, "erased": 0, "len": len(g), "events": [], "answer": a.answer}
            if n_params:
                r["flops"] = 2.0 * n_params * toks
            results.append(r)
    return results


def decode_majority(model, problems, tok, device, k, batch_size=128, amp_dtype=None, max_sol_len=600,
                    temperature=0.7, n_params=None):
    """Plain model + self-consistency (majority vote over k samples)."""
    flat = [p for p in problems for _ in range(k)]
    res = decode_plain(model, flat, tok, device, batch_size, amp_dtype, max_sol_len, temperature, n_params)
    out = []
    for i, p in enumerate(problems):
        rs = res[i * k:(i + 1) * k]
        votes = collections.Counter(r["answer"] for r in rs if r["answer"] is not None)
        ans = votes.most_common(1)[0][0] if votes else None
        r = {"idx": i, "op": p.n_ops, "correct": ans == p.answer, "complete": ans is not None,
             "sol_correct": any(x["sol_correct"] for x in rs), "steps": sum(x["steps"] for x in rs),
             "tokens": sum(x["tokens"] for x in rs), "fixes": 0, "fills": 0, "erased": 0,
             "len": sum(x["len"] for x in rs) / k, "events": [], "k": k}
        if n_params:
            r["flops"] = 2.0 * n_params * r["tokens"]
        out.append(r)
    return out


@torch.no_grad()
def calibrate_tau_err(model, problems, tok, device, window, amp_dtype=None, false_per_problem=0.5, stride=4,
                      batch_size=64, max_sol_len=600, require_disagree=True, writer=None):
    """Pick the error threshold on the model's own greedy solutions (held-out
    problems): the largest-scoring position of every window that contains no
    error yet is a would-be false fix; the threshold is the quantile that
    allows `false_per_problem` false fixes per solution. Also reports the
    fraction of windows containing the first error whose top-scoring position
    is that error and clears the threshold (= detection recall)."""
    runner = Runner(model, tok, device, amp_dtype, writer=writer)
    gens, _ = generate(runner.writer, [p.prompt_ids for p in problems], max_sol_len, tok.eos, tok.pad, device,
                       amp_dtype=amp_dtype)
    items, kinds = [], []  # kind: (is_positive, error index within window or -1)
    n_steps = 0
    for p, g in zip(problems, gens):
        a = analyze(p, g, tok)
        j = a.first_err
        n_steps += len(g)
        P = len(p.prompt_ids)
        for t in range(1, len(g) + 1, stride):
            ws = max(0, t - window)
            if j is None or t <= j:
                items.append((p.prompt_ids + g[:t], g[ws:t], P + ws))
                kinds.append((False, -1))
            elif j >= ws:
                items.append((p.prompt_ids + g[:t], g[ws:t], P + ws))
                kinds.append((True, j - ws))
    neg, pos = [], []
    for s in range(0, len(items), batch_size):
        out = runner.forward(items[s:s + batch_size])
        err = out["err"].masked_fill(~out["cvalid"], 0.0)
        bad = (out["ctok"] == tok.mask) | (out["ctok"] == tok.null)
        if require_disagree:
            bad = bad | ~out["disagree"]
        err = err.masked_fill(bad, 0.0)
        mx, arg = err.max(-1)
        mx, arg = mx.tolist(), arg.tolist()
        for r, (is_pos, jw) in enumerate(kinds[s:s + batch_size]):
            if is_pos:
                pos.append(mx[r] if arg[r] == jw else 0.0)
            else:
                neg.append(mx[r])
    # each negative window stands for `stride` decoding steps
    n_solutions = max(1, len(problems))
    allowed = false_per_problem * n_solutions / max(1, stride)
    neg_sorted = sorted(neg, reverse=True)
    k = int(allowed)
    tau = neg_sorted[k] if k < len(neg_sorted) else 0.0
    tau = float(min(0.95, max(0.02, tau + 1e-6)))
    recall = sum(1 for x in pos if x > tau) / max(1, len(pos))
    return {"tau_err": tau, "detect_recall": recall, "n_pos_windows": len(pos), "n_neg_windows": len(neg),
            "greedy_acc": sum(analyze(p, g, tok).correct for p, g in zip(problems, gens)) / max(1, len(problems)),
            "mean_pos_score": sum(pos) / max(1, len(pos)), "false_per_problem": false_per_problem}
